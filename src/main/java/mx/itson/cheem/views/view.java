    private void BtnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnActualizarActionPerformed
        // TODO add your handling code here:
        if (jTableAnime.isEditing()) {
            jTableAnime.getCellEditor().stopCellEditing();
        }

        int fila = jTableModificar.getSelectedRow();
        if (fila == -1) {
            JOptionPane.showMessageDialog(this, "Selecciona una fila para actualizar.", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            DefaultTableModel modelo = (DefaultTableModel) jTableAnime.getModel();
            int idAnime = Integer.parseInt(modelo.getValueAt(fila, 0).toString());
            Object nombreObj = modelo.getValueAt(fila, 1);
            Object anioObj = modelo.getValueAt(fila, 2);

            JsonObject json = new JsonObject();
            json.addProperty("nombre", nombreObj != null ? nombreObj.toString() : "");
            json.addProperty("anio", anioObj != null ? anioObj.toString() : "");

            HttpRequest request = HttpRequest.newBuilder()
            .uri(URI.create("http://127.0.0.1:8000/update_anime/" + idAnime + "/"))
            .header("Content-Type", "application/json")
            .PUT(HttpRequest.BodyPublishers.ofString(json.toString()))
            .build();

            HttpResponse<String> response = HttpClient.newHttpClient()
            .send(request, HttpResponse.BodyHandlers.ofString());

            int status = response.statusCode();
            String body = response.body();

            System.out.println("Codigo de estado: " + status);
            System.out.println("Respuesta del servidor: " + body);

            if (status >= 200 && status < 300) {
                JOptionPane.showMessageDialog(this, "Anime actualizado correctamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
                cargarAnimes();
            } else {
                JOptionPane.showMessageDialog(this, body, "Error (" + status + ")", JOptionPane.ERROR_MESSAGE);
                cargarAnimes();
            }

        } catch (IOException ex) {
            System.err.println("Error de conexión/E/S: " + ex.getMessage());
            JOptionPane.showMessageDialog(this, "No se pudo conectar al servidor.", "Error de conexión", JOptionPane.ERROR_MESSAGE);
        } catch (InterruptedException ex) {
            System.err.println("Llamada interrumpida: " + ex.getMessage());
            Thread.currentThread().interrupt();
        }
    }//GEN-LAST:event_BtnActualizarActionPerformed

