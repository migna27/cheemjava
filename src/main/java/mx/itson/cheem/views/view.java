    private void cargarAnimes() {
    try {
        HttpRequest request = HttpRequest.newBuilder()
                .uri(URI.create("http://127.0.0.1:8000/get_animes/"))
                .GET()
                .build();

        HttpResponse<String> response = HttpClient.newHttpClient()
                .send(request, HttpResponse.BodyHandlers.ofString());

        int status = response.statusCode();
        String body = response.body();

        System.out.println("Codigo de estado: " + status);
        System.out.println("Respuesta del servidor: " + body);

        if (status >= 200 && status < 300) {
            Gson gson = new Gson();
            JsonObject jsonObject = JsonParser.parseString(body).getAsJsonObject();
            JsonArray jsonArray = jsonObject.getAsJsonArray("animes");

            Anime[] lista = gson.fromJson(jsonArray, Anime[].class);

            DefaultTableModel modelo = (DefaultTableModel) jTableAnime.getModel();
            modelo.setRowCount(0);

            for (Anime a : lista) {
                modelo.addRow(new Object[]{a.getId(), a.getNombre(), a.getAnio()});
            }
        } else {
            JOptionPane.showMessageDialog(this, body, "Error (" + status + ")", JOptionPane.ERROR_MESSAGE);
        }

    } catch (IOException ex) {
        System.err.println("Error de conexión/E/S: " + ex.getMessage());
        JOptionPane.showMessageDialog(this, "No se pudo conectar al servidor.", "Error de conexión", JOptionPane.ERROR_MESSAGE);
    } catch (InterruptedException ex) {
        System.err.println("Llamada interrumpida: " + ex.getMessage());
        Thread.currentThread().interrupt();
    }
}
